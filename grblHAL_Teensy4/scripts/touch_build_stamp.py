"""
PlatformIO pre-build script: regenerates src/build_stamp.h with the current
local timestamp AND git provenance on every build, so the [BUILD:...] line
emitted in $I (see report.c::report_build_info) refreshes whenever you
rebuild and tells you exactly which repo/branch/commit produced the firmware.

Why a generated header instead of touch+__DATE__/__TIME__?
SCons (which PlatformIO drives) detects "changed" by content hash, not
mtime - `os.utime`-ing report.c doesn't invalidate report.o. But writing
a different value into a header that report.c includes does: SCons sees
build_stamp.h changed -> report.c gets recompiled -> the new BUILD_TIMESTAMP
string is embedded in report.o.

report.c prints BUILD_TIMESTAMP verbatim inside [BUILD:...], so all the
provenance lives in this one string - no core/report.c change needed. We
rewrite build_stamp.h unconditionally; the content always differs between
runs (timestamps include seconds), so SCons always invalidates report.c.

Provenance captured:
  drv:<branch>@<short-sha>  - the driver repo (iMXRT1062) checkout
  grbl:<describe>           - the grbl submodule (usually detached HEAD, so
                              git describe --all gives heads/<branch> when on
                              a branch tip, else an abbreviated SHA); a -dirty
                              suffix flags uncommitted overlay edits
git is optional: if it is missing or this isn't a repo, the helper returns
"?" and the build still succeeds (timestamp-only stamp).
"""

Import("env")

import datetime
import pathlib
import subprocess


def git(*args, cwd):
    try:
        out = subprocess.check_output(["git", *args], cwd=str(cwd),
                                      stderr=subprocess.DEVNULL).decode().strip()
        # git refs can't contain " or \, but keep the C string literal safe regardless
        return out.replace("\\", "").replace('"', "") or "?"
    except Exception:
        return "?"


proj = pathlib.Path(env.subst("$PROJECT_DIR"))            # grblHAL_Teensy4
stamp_h = proj / "src" / "build_stamp.h"
now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

def ref(cwd):
    # "<branch-or-tag>@<short-sha>" (+ "-dirty"), so the BUILD line distinguishes
    # commits, not just branch names. Submodules are usually detached HEAD, so the
    # name comes from `git describe --all` (heads/<branch> at a tip, else a tag/sha);
    # strip the heads/remotes prefix and append the short sha. If describe already
    # resolved to the sha (detached, no ref), don't repeat it.
    name = git("describe", "--all", "--always", "--dirty", cwd=cwd).replace("heads/", "").replace("remotes/", "")
    sha = git("rev-parse", "--short", "HEAD", cwd=cwd)
    return name if (sha == "?" or sha in name) else "{}@{}".format(name, sha)


drv = ref(proj)
grbl = ref(proj / "src" / "grbl")

stamp = "{} drv:{} grbl:{}".format(now, drv, grbl)


def semver(cwd):
    """The firmware's own version, from the nearest v<major>.<minor>.<patch> TAG.

    This replaces the hand-edited GRBL_BUILD literal that used to sit in grbl.h. A
    date typed in by hand answered neither question anyone asked: it did not move
    when the code moved (two different builds shared it), and it was not a version
    anybody had decided on. A tag is the opposite on both counts - a human bumps it
    deliberately, and git then derives everything else.

    No tag yet (a fresh clone, or a branch before the first release) gives 0.0.0,
    which reads as "unversioned build" rather than pretending to a number. The sha
    and dirty flag in BUILD_TIMESTAMP still identify it exactly.
    """
    tag = git("describe", "--tags", "--match", "v[0-9]*", "--abbrev=0", cwd=cwd)
    parts = tag.lstrip("v").split(".") if tag != "?" else []
    out = []
    for i in range(3):
        try:
            out.append(int(parts[i]))
        except (IndexError, ValueError):
            out.append(0)
    return out


major, minor, patch = semver(proj)

stamp_h.write_text(
    "/* Auto-generated by scripts/touch_build_stamp.py - do not edit. */\n"
    "#pragma once\n"
    '#define BUILD_TIMESTAMP "{}"\n'
    "\n"
    "/* Firmware version, derived from the nearest v*.*.* git tag - never hand-edited.\n"
    "   FIRMWARE_VERSION_NUM is the monotonic integer form, for code that needs to\n"
    "   compare versions (it is what replaced GRBL_BUILD's numeric role). */\n"
    "#define FIRMWARE_VERSION_MAJOR {}\n"
    "#define FIRMWARE_VERSION_MINOR {}\n"
    "#define FIRMWARE_VERSION_PATCH {}\n"
    '#define FIRMWARE_VERSION "{}.{}.{}"\n'
    "#define FIRMWARE_VERSION_NUM ({}L * 10000 + {}L * 100 + {}L)\n".format(
        stamp, major, minor, patch, major, minor, patch, major, minor, patch)
)

print("build-stamp: wrote {} = {} (fw {}.{}.{})".format(
    stamp_h.relative_to(proj), stamp, major, minor, patch))
